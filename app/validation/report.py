"""Validation report models for the AI validation module."""

from typing import Literal

from pydantic import BaseModel, Field


IssueSeverity = Literal["error", "warning"]


class ValidationIssue(BaseModel):
    """Structured description of one validation issue.

    Parameters:
        code: Stable machine-readable validation code.
        field_path: Dot-separated path to the affected field.
        message: Human-readable validation message.
        severity: Issue severity. Errors invalidate the FeatureVector.

    Returns:
        A Pydantic model representing one validation issue.

    Exceptions:
        pydantic.ValidationError: Raised when issue data is malformed.
    """

    code: str
    field_path: str
    message: str
    severity: IssueSeverity = "error"


class ValidationReport(BaseModel):
    """Stores the result of validating a FeatureVector.

    Parameters:
        is_valid: True when no validation errors were found.
        errors: Error-level validation issues.
        warnings: Warning-level validation issues.

    Returns:
        A report object that can be inspected by callers or attached to
        validation exceptions.

    Exceptions:
        pydantic.ValidationError: Raised when report data is malformed.
    """

    is_valid: bool = True
    errors: list[ValidationIssue] = Field(default_factory=list)
    warnings: list[ValidationIssue] = Field(default_factory=list)

    @property
    def error_count(self) -> int:
        """Return the number of error-level validation issues.

        Parameters:
            None.

        Returns:
            Number of errors currently stored in the report.

        Exceptions:
            None.
        """

        return len(self.errors)

    @property
    def warning_count(self) -> int:
        """Return the number of warning-level validation issues.

        Parameters:
            None.

        Returns:
            Number of warnings currently stored in the report.

        Exceptions:
            None.
        """

        return len(self.warnings)

    def add_error(
        self,
        code: str,
        field_path: str,
        message: str,
    ) -> None:
        """Add an error-level validation issue.

        Parameters:
            code: Stable machine-readable validation code.
            field_path: Dot-separated path to the affected field.
            message: Human-readable validation message.

        Returns:
            None.

        Exceptions:
            pydantic.ValidationError: Raised when issue data is malformed.
        """

        self.is_valid = False
        self.errors.append(
            ValidationIssue(
                code=code,
                field_path=field_path,
                message=message,
                severity="error",
            )
        )

    def add_warning(
        self,
        code: str,
        field_path: str,
        message: str,
    ) -> None:
        """Add a warning-level validation issue.

        Parameters:
            code: Stable machine-readable validation code.
            field_path: Dot-separated path to the affected field.
            message: Human-readable validation message.

        Returns:
            None.

        Exceptions:
            pydantic.ValidationError: Raised when issue data is malformed.
        """

        self.warnings.append(
            ValidationIssue(
                code=code,
                field_path=field_path,
                message=message,
                severity="warning",
            )
        )

    def extend(self, issues: list[ValidationIssue]) -> None:
        """Add multiple validation issues to this report.

        Parameters:
            issues: Validation issues generated by validation rules.

        Returns:
            None.

        Exceptions:
            None.
        """

        for issue in issues:
            if issue.severity == "warning":
                self.warnings.append(issue)
            else:
                self.is_valid = False
                self.errors.append(issue)
